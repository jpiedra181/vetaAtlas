const dicts: Record<Lang, Dict> = { es, en };

let current: Lang = detect();
const listeners = new Set<() => void>();

function detect(): Lang {
  const q = new URLSearchParams(location.search).get('lang');
  if (q === 'en' || q === 'es') return q;
  try {
    const s = localStorage.getItem('veta:lang');
    if (s === 'en' || s === 'es') return s;
  } catch {}
  return navigator.language?.toLowerCase().startsWith('es') ? 'es' : navigator.language ? 'en' : 'es';
}

export const lang = () => current;

export function setLang(l: Lang) {
  if (l === current) return;
  current = l;
  try { localStorage.setItem('veta:lang', l); } catch {}
  document.documentElement.lang = l;
  document.title = t('meta.title');
  listeners.forEach((fn) => fn());
}

export const onLang = (fn: () => void) => (listeners.add(fn), () => listeners.delete(fn));

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s: string = dicts[current][key] ?? dicts.es[key] ?? key;
  if (vars) for (const k in vars) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}

/** Plural helper for keys that have a `.one` variant. */
export function tn(key: 'atlas.count' | 'filters.show' | 'sel.count', n: number) {
  return n === 1 ? t(`${key}.one` as Key) : t(key, { n });
}

export const num = (n: number, digits = 0) =>
  n.toLocaleString(current === 'es' ? 'es-ES' : 'en-GB', { minimumFractionDigits: digits, maximumFractionDigits: digits });

/** Fill [data-i18n] text and [data-i18n-attr="attr:key;attr2:key2"] attributes. */
export function applyI18n(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n as Key);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-attr]').forEach((el) => {
    for (const pair of el.dataset.i18nAttr!.split(';')) {
      const [attr, key] = pair.split(':');
      el.setAttribute(attr.trim(), t(key.trim() as Key));
    }
  });
}
